/**
 * Returnează metadatele unui senzor pe baza cheii sau a numelui său
 */
export function getSensorInfo(keyOrLabel) {
    if (!keyOrLabel) return null;
    
    // 1. Căutare directă după cheie exactă
    if (SENSOR_DICTIONARY[keyOrLabel]) {
        return SENSOR_DICTIONARY[keyOrLabel];
    }

    // 2. Căutare după label parțial sau similar
    const cleanSearch = keyOrLabel.toLowerCase().trim();
    for (const [key, item] of Object.entries(SENSOR_DICTIONARY)) {
        if (
            key.toLowerCase() === cleanSearch ||
            item.name.toLowerCase().includes(cleanSearch) ||
            cleanSearch.includes(item.name.toLowerCase())
        ) {
            return item;
        }
    }

    // 3. Fallback generic inteligent
    return {
        name: keyOrLabel,
        icon: 'analytics-outline',
        category: 'TELEMETRIE CAN-BUS',
        unit: '',
        isVirtual: false,
        nominalRange: 'Parametru monitorizat în timp real conform specificațiilor ECU',
        whatItIs: `Parametru de telemetrie transmis live prin protocolul OBD-II/UDS de calculatorul de bord al vehiculului.`,
        whyItMatters: 'Monitorizarea acestui parametru permite detectarea anomaliilor funcționale și menținerea motorului în parametri optimi.',
        symptoms: 'Deviațiile persistente față de intervalul nominal pot indica uzură de componente sau neconcordanțe pe senzori.',
        formula: 'f(CAN_BUS_PID)',
    };
}
